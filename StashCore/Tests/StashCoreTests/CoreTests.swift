import XCTest
@testable import StashCore

final class CoreTests: XCTestCase {
    func testExactColorRules() {
        for value in ["#1A2B3C", "1a2b3c", "ABCDEF", "#235442"] { XCTAssertEqual(ContentClassifier.kind(for: value), .color, value) }
        for value in ["235442", "#FFF", "rgb(1,2,3)", "red", "the #ABCDEF color", " ABCDEF ", "#abcdeg", "https://example.com/#AABBCC"] { XCTAssertNotEqual(ContentClassifier.kind(for: value), .color, value) }
        XCTAssertEqual(ContentClassifier.kind(for: "https://example.com"), .link)
    }
    func testPrivacyDefaults() {
        let settings = LibrarySettings()
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] { XCTAssertFalse(CapturePolicy.allows(types: [type], app: "com.example", settings: settings, now: .now)) }
        XCTAssertFalse(CapturePolicy.allows(types: [], app: "com.agilebits.onepassword7", settings: settings, now: .now))
        XCTAssertTrue(CapturePolicy.allows(types: [], app: "com.apple.TextEdit", settings: settings, now: .now))
    }
    func testTimedPauseAndResume() {
        var settings = LibrarySettings(); let date = Date(timeIntervalSince1970: 10_000)
        settings.pausedUntil = date.addingTimeInterval(900)
        XCTAssertFalse(CapturePolicy.allows(types: [], app: nil, settings: settings, now: date))
        XCTAssertTrue(CapturePolicy.allows(types: [], app: nil, settings: settings, now: date.addingTimeInterval(901)))
    }
    func testPinnedItemsSurviveRetention() {
        let now = Date(); var old = ClipItem(kind: .text, text: "keep", createdAt: now.addingTimeInterval(-100 * 86400))
        XCTAssertEqual(Retention.action(for: old, days: 30, now: now), .delete)
        old.pinboardID = UUID()
        XCTAssertEqual(Retention.action(for: old, days: 30, now: now), .removeFromHistory)
        XCTAssertEqual(Retention.action(for: old, days: nil, now: now), .keep)
    }
    func testStackConsumesOnceAndReverses() {
        var stack = PasteStack(); let a = UUID(), b = UUID()
        stack.start(); stack.append(a); stack.append(b)
        XCTAssertEqual(stack.next, a); stack.reverse()
        XCTAssertEqual(stack.consume(), b); XCTAssertEqual(stack.consume(), a); XCTAssertNil(stack.consume())
        stack.stop(); stack.append(a); XCTAssertTrue(stack.items.isEmpty)
    }
    func testArchiveRoundTripAndVersionValidation() throws {
        let item = ClipItem(kind: .text, text: "مرحبا \"world\"")
        let archive = LibraryArchive(items: [item], pinboards: [], settings: LibrarySettings())
        let restored = try LibraryArchive.decode(archive.encode())
        XCTAssertEqual(restored.items.first?.text, item.text)
        let data = try JSONSerialization.data(withJSONObject: ["version": 999, "items": [], "pinboards": []])
        XCTAssertThrowsError(try LibraryArchive.decode(data))
    }
    @MainActor func testSearchIncludesOCRAndSafelyHandlesSyntax() throws {
        let index = try SearchIndex(url: nil)
        var image = ClipItem(kind: .image, text: ""); image.ocrText = "invoice Cairo"; image.sourceAppName = "Preview"
        let note = ClipItem(kind: .text, text: "launch notes")
        try index.rebuild([image, note])
        XCTAssertEqual(try index.search("invoice").first, image.id)
        XCTAssertEqual(try index.search("launch").first, note.id)
        XCTAssertEqual(try index.search("\" OR * ("), [])
        try index.remove(image.id); XCTAssertTrue(try index.search("invoice").isEmpty)
    }
    func testMCPReadScopesAreIndependent() {
        var history = ClipItem(kind:.text,text:"history")
        let boardReader = MCPClient(name:"Board client",scopes:[.readPinboards])
        let historyReader = MCPClient(name:"History client",scopes:[.readHistory])
        let writer = MCPClient(name:"Writer",scopes:[.writeItems])
        XCTAssertFalse(boardReader.canRead(history)); XCTAssertTrue(historyReader.canRead(history)); XCTAssertFalse(writer.canRead(history))
        history.pinboardID = UUID(); history.isInHistory = false
        XCTAssertTrue(boardReader.canRead(history)); XCTAssertFalse(historyReader.canRead(history)); XCTAssertFalse(writer.canRead(history))
    }

}
