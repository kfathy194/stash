import Foundation

public enum ContentClassifier {
    public static func kind(for text: String) -> ClipKind {
        if text.range(of: "^#[0-9a-fA-F]{6}$", options: .regularExpression) != nil { return .color }
        if text.range(of: "^[0-9a-fA-F]{6}$", options: .regularExpression) != nil, text.range(of: "[a-fA-F]", options: .regularExpression) != nil { return .color }
        if !text.contains(where: \.isWhitespace), let url = URL(string: text), ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil { return .link }
        return .text
    }
}

public enum CapturePolicy {
    public static func allows(types: [String], app: String?, settings: LibrarySettings, now: Date) -> Bool {
        guard !settings.isPaused(at: now) else { return false }
        if let app, settings.ignoredApplications.contains(app) { return false }
        if settings.ignoreConfidential && types.contains("org.nspasteboard.ConcealedType") { return false }
        if settings.ignoreTransient && types.contains(where: { ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].contains($0) }) { return false }
        return true
    }
}

public enum Retention {
    public enum Action { case keep, delete, removeFromHistory }
    public static func action(for item: ClipItem, days: Int?, now: Date) -> Action {
        guard let days, item.createdAt < now.addingTimeInterval(-Double(days) * 86400) else { return .keep }
        return item.pinboardID == nil ? .delete : .removeFromHistory
    }
}

public struct PasteStack: Sendable {
    public private(set) var isActive = false
    public private(set) var items: [UUID] = []
    public init() {}
    public var next: UUID? { items.first }
    public mutating func start() { isActive = true; items.removeAll() }
    public mutating func stop() { isActive = false; items.removeAll() }
    public mutating func append(_ id: UUID) { if isActive { items.append(id) } }
    public mutating func reverse() { items.reverse() }
    public mutating func remove(_ id: UUID) { items.removeAll { $0 == id } }
    public mutating func consume() -> UUID? { items.isEmpty ? nil : items.removeFirst() }
}
